import { describe, expect, it } from "vitest";
import { findDeadLeads } from "../src/lib/dormancy";
import { Importer } from "../src/lib/import";
import { offsetFromHeader, parseMetaDate, parseMetaHtml } from "../src/lib/parsers/meta-html";
import { NOW, zip } from "./helpers";

/**
 * Same layout as a real Facebook HTML export (Oct 2026), with made-up people.
 * Class names copied from the real file; the reader must not depend on them.
 */
function page(title: string, owner: string, msgs: { from?: string; text?: string; date: string; img?: boolean; react?: string }[]) {
  const sections = msgs
    .map(
      (m) => `<section class="_a6-g" aria-labelledby="u_0_1"><h2 class="_2ph_ _a6-h _a6-i">${m.from ?? ""}</h2>` +
        `<div class="_2ph_ _a6-p"><div><div></div><div>${m.text ?? ""}${m.img ? '<img src="photos/1.jpg" />' : ""}</div><div></div>` +
        `${m.react ? `<ul class="_a6-q"><li>${m.react}</li></ul>` : ""}<div></div></div></div>` +
        `<footer class="_3-94 _a6-o"><div class="_a72d">${m.date}</div></footer></section>`,
    )
    .join("");
  return `<html><head><meta charset="utf-8" /><base href="../../../../" /><style>._a6-g{}</style><title>${title}</title></head>` +
    `<body class="_5vb_ _2yq _a7o5"><div class="_li"><div class="_a705"><header class="_as-_ _a709"><div class="_a70d"><h1>${title}</h1>` +
    `<aside class="_aoaa">Generated by ${owner} on <time>Tuesday, October 20, 2026 at 9:49 PM UTC+01:00</time></aside></div></header>` +
    `<main class="_a706">${sections}</main></div></div></body></html>`;
}

describe("Facebook HTML export", () => {
  it("reads dates in the export's own time zone", () => {
    expect(offsetFromHeader("on Tuesday, October 20, 2026 at 9:49 PM UTC+01:00")).toBe(60);
    expect(offsetFromHeader("at 9:49 AM UTC-04:00")).toBe(-240);
    expect(parseMetaDate("Mar 05, 2026 4:44:47 pm", 60)).toBe(Date.UTC(2026, 2, 5, 15, 44, 47));
    expect(parseMetaDate("Dec 31, 2025 12:05:00 am", 0)).toBe(Date.UTC(2025, 11, 31, 0, 5, 0));
  });

  it("reads senders, text with entities, media, reactions, system lines and the owner", () => {
    const html = page("Grace Mensah", "Layla Haddad", [
      { from: "Grace Mensah", text: "Is the 3 bed in Lekki still available? Budget &#x20a6;150m &amp; I can view Saturday", date: "Mar 05, 2026 4:44:47 pm", react: "❤ Layla Haddad" },
      { from: "Layla Haddad", text: "Yes it is!", date: "Mar 05, 2026 5:01:02 pm" },
      { from: "Grace Mensah", img: true, date: "Mar 05, 2026 5:02:00 pm" },
      { from: "Layla Haddad", text: "You're now connected on Messenger", date: "Mar 01, 2026 9:00:00 am" },
      { from: "Grace Mensah", text: "This message was unsent", date: "Mar 06, 2026 9:00:00 am" },
      { text: "", date: "Mar 06, 2026 9:01:00 am" },
    ]);
    const r = parseMetaHtml(html, "facebook-x/your_facebook_activity/messages/inbox/gracemensah_123/message_1.html")!;
    expect(r.owner).toBe("Layla Haddad");
    expect(r.part.channel).toBe("facebook");
    expect(r.part.folder).toBe("inbox");
    expect(r.part.counterpart).toBe("Grace Mensah");
    const [ask, yes, photo, connected, unsent, blank] = r.part.messages;
    expect(ask!.text).toBe("Is the 3 bed in Lekki still available? Budget ₦150m & I can view Saturday");
    expect(ask!.kind).toBe("text");
    expect(yes!.kind).toBe("text");
    expect(photo!.kind).toBe("media");
    expect(connected!.kind).toBe("system");
    expect(unsent!.kind).toBe("unsent");
    expect(blank!.sender).toBeNull();
  });

  it("never mistakes real messages for group notices", () => {
    const html = page("Tom Reid", "Layla Haddad", [
      { from: "Tom Reid", text: "I left you a voicemail about the villa", date: "Mar 05, 2026 4:44:47 pm" },
      { from: "Tom Reid", text: "My wife added the condo to our shortlist", date: "Mar 05, 2026 4:45:00 pm" },
      { from: "Tom Reid", text: "Tom Reid left the group.", date: "Mar 05, 2026 4:46:00 pm" },
    ]);
    const kinds = parseMetaHtml(html, "x/messages/inbox/tom_1/message_1.html")!.part.messages.map((m) => m.kind);
    expect(kinds).toEqual(["text", "text", "system"]);
  });

  it("imports a whole HTML export: chats in every folder, owner known, other pages skipped quietly", async () => {
    const root = "your_facebook_activity/messages";
    const archive = zip({
      [`${root}/inbox/grace_1/message_1.html`]: page("Grace Mensah", "Layla Haddad", [
        { from: "Layla Haddad", text: "Hello Grace", date: "Jan 05, 2026 4:44:47 pm" },
        { from: "Grace Mensah", text: "Do you have 2 bed apartments to rent in Yaba?", date: "Jan 05, 2026 5:00:00 pm" },
      ]),
      [`${root}/message_requests/obi_2/message_1.html`]: page("Obi Okafor", "Layla Haddad", [
        { from: "Obi Okafor", text: "Price for the duplex?", date: "Feb 01, 2026 10:00:00 am" },
      ]),
      [`${root}/e2ee_cutover_archived/ada_3/message_1.html`]: page("Ada Eze", "Layla Haddad", [
        { from: "Layla Haddad", text: "New listing in Ikoyi", date: "Feb 02, 2026 10:00:00 am" },
      ]),
      [`${root}/your_messages.html`]: "<html><body><h1>Your messages</h1></body></html>",
      "preferences/preferences/settings.html": "<html><body>settings</body></html>",
      [`${root}/inbox/grace_1/photos/1.jpg`]: new Uint8Array(1000),
    });
    const imp = new Importer();
    await imp.addFile("facebook-layla-20_10_2026.zip", archive);
    const res = imp.finish();
    expect(res.self.facebook).toEqual(["Layla Haddad"]);
    expect(res.warnings).toEqual([]);
    expect(res.conversations.map((c) => c.folder).sort()).toEqual(["e2ee_cutover_archived", "inbox", "message_requests"]);
    const verdicts = findDeadLeads(res.leads, { now: NOW });
    const name = (id: string) => res.leads.find((l) => l.id === id)!.name;
    expect(verdicts.filter((v) => v.status === "dead").map((v) => name(v.leadId)).sort()).toEqual(["Grace Mensah", "Obi Okafor"]);
    expect(verdicts.find((v) => name(v.leadId) === "Ada Eze")!.excludeReason).toBe("lead_never_wrote");
  });
});
